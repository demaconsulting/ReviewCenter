using System.Globalization;
using System.Text;
using System.Text.Json;

namespace DemaConsulting.ReviewCenter.Core;

/// <summary>
///     Formats the entries of an audit export as CSV or JSON, one batch at a time.
/// </summary>
/// <remarks>
///     <para>
///         The writer is pure: it knows nothing of HTTP or of the store. It collects the bytes of the batch it was
///         given in a small buffer, and the caller copies the buffer to the target with
///         <see cref="FlushToAsync"/>, so the target can be a stream that only accepts asynchronous writes and no
///         more than one batch is ever held in memory. A document is written by calling <see cref="WriteStart"/>
///         once, <see cref="WriteEntries"/> for each batch and <see cref="WriteEnd"/> once.
///     </para>
///     <para>
///         CSV: UTF-8 with a byte order mark (so a spreadsheet opens it as UTF-8), CRLF line endings and RFC 4180
///         quoting (a cell with a comma, a quote, a CR or an LF is quoted and its quotes are doubled). The columns
///         are <c>sequence,timestampUtc,actor,action,project,review,detail,previousHash,hash</c>; timestamps are
///         ISO 8601 round-trip (<c>O</c>) in UTC. A spreadsheet treats a cell that starts with <c>=</c>, <c>+</c>,
///         <c>-</c>, <c>@</c>, a tab or a CR as a formula, and the text cells hold text chosen by people (an actor
///         name, a detail), so every such text cell (actor, action, review, detail) is prefixed with a single quote
///         (<c>'</c>) to neutralize it. The sequence, the timestamp, the project number and the two hashes are
///         generated by the system and are never changed, so the hashes can be re-checked as they are. The prefix
///         is part of the file only; nothing stored changes.
///     </para>
///     <para>
///         JSON: one document, <c>{ "export": { "generatedUtc", "filter" }, "chain": { "status",
///         "firstBrokenSequence" }, "entries": [ ... ] }</c>, written with <see cref="Utf8JsonWriter"/> (no
///         byte order mark, no formula neutralization because JSON is not opened in a spreadsheet). Only the set
///         parts of the filter appear. The chain object holds the status and, for a broken chain, the first
///         broken sequence, and never a count or the head hash, because the chain is global and a count would
///         reveal how much other projects did.
///     </para>
///     The class is not thread-safe; use one instance per export, and dispose it to return the buffers of the JSON
///     writer.
/// </remarks>
public sealed class AuditExportWriter : IDisposable
{
    /// <summary>
    ///     The characters that start a cell a spreadsheet could take as a formula.
    /// </summary>
    private static readonly char[] FormulaStarts = ['=', '+', '-', '@', '\t', '\r'];

    /// <summary>
    ///     The characters that make a CSV cell need quoting.
    /// </summary>
    private static readonly char[] QuotedChars = [',', '"', '\r', '\n'];

    /// <summary>
    ///     The UTF-8 encoding without a byte order mark; the mark is written once, explicitly.
    /// </summary>
    private static readonly UTF8Encoding Utf8 = new(false);

    /// <summary>
    ///     The export being written.
    /// </summary>
    private readonly AuditExport _export;

    /// <summary>
    ///     The bytes of the current batch that were not yet passed on.
    /// </summary>
    private readonly MemoryStream _buffer = new();

    /// <summary>
    ///     The JSON writer on <see cref="_buffer"/>; <c>null</c> for CSV.
    /// </summary>
    private readonly Utf8JsonWriter? _json;

    /// <summary>
    ///     Initializes a new instance of the <see cref="AuditExportWriter"/> class.
    /// </summary>
    /// <param name="export">The export to write; its format, filter, chain status and time are used. Must not be null.</param>
    /// <exception cref="ArgumentNullException">Thrown when <paramref name="export"/> is null.</exception>
    public AuditExportWriter(AuditExport export)
    {
        ArgumentNullException.ThrowIfNull(export);
        _export = export;
        _json = export.Format == AuditExportFormat.Json
            ? new Utf8JsonWriter(_buffer, new JsonWriterOptions { Indented = false })
            : null;
    }

    /// <summary>
    ///     Writes what comes before the entries: the byte order mark and header row (CSV), or the export
    ///     description, the chain status and the start of the entries array (JSON).
    /// </summary>
    public void WriteStart()
    {
        if (_json is null)
        {
            // The mark tells spreadsheets that the file is UTF-8
            _buffer.Write(Encoding.UTF8.Preamble);
            AppendCsvLine(
                "sequence", "timestampUtc", "actor", "action", "project", "review", "detail", "previousHash", "hash");
            return;
        }

        _json.WriteStartObject();
        _json.WriteStartObject("export");
        _json.WriteString("generatedUtc", _export.GeneratedUtc.UtcDateTime.ToString("O", CultureInfo.InvariantCulture));
        WriteJsonFilter(_json, _export.Filter);
        _json.WriteEndObject();

        _json.WriteStartObject("chain");
        _json.WriteString("status", _export.ChainStatus);
        if (_export.FirstBrokenSequence is { } broken)
        {
            _json.WriteNumber("firstBrokenSequence", broken);
        }

        _json.WriteEndObject();
        _json.WriteStartArray("entries");
    }

    /// <summary>
    ///     Writes one batch of entries, in the order given.
    /// </summary>
    /// <param name="entries">The entries to write. Must not be null.</param>
    /// <exception cref="ArgumentNullException">Thrown when <paramref name="entries"/> is null.</exception>
    public void WriteEntries(IEnumerable<AuditEntry> entries)
    {
        ArgumentNullException.ThrowIfNull(entries);
        foreach (var entry in entries)
        {
            if (_json is null)
            {
                AppendCsvLine(
                    entry.Sequence.ToString(CultureInfo.InvariantCulture),
                    Timestamp(entry),
                    Neutralize(entry.ActorName),
                    Neutralize(entry.Action),
                    entry.ProjectId?.ToString(CultureInfo.InvariantCulture) ?? string.Empty,
                    Neutralize(entry.ReviewId ?? string.Empty),
                    Neutralize(entry.Detail),
                    entry.PreviousHash,
                    entry.Hash);
                continue;
            }

            _json.WriteStartObject();
            _json.WriteNumber("sequence", entry.Sequence);
            _json.WriteString("timestampUtc", Timestamp(entry));
            _json.WriteString("actor", entry.ActorName);
            _json.WriteString("action", entry.Action);
            WriteNullable(_json, "project", entry.ProjectId);
            _json.WriteString("review", entry.ReviewId);
            _json.WriteString("detail", entry.Detail);
            _json.WriteString("previousHash", entry.PreviousHash);
            _json.WriteString("hash", entry.Hash);
            _json.WriteEndObject();
        }
    }

    /// <summary>
    ///     Writes what comes after the last entry: nothing for CSV, the end of the array and the document for JSON.
    /// </summary>
    public void WriteEnd()
    {
        if (_json is null)
        {
            return;
        }

        _json.WriteEndArray();
        _json.WriteEndObject();
    }

    /// <summary>
    ///     Copies everything written since the last call to the target and empties the buffer.
    /// </summary>
    /// <param name="target">The stream to write to. Must not be null.</param>
    /// <param name="cancellationToken">Cancels the operation.</param>
    /// <returns>A task that completes when the bytes were handed to the target.</returns>
    /// <exception cref="ArgumentNullException">Thrown when <paramref name="target"/> is null.</exception>
    public async Task FlushToAsync(Stream target, CancellationToken cancellationToken = default)
    {
        ArgumentNullException.ThrowIfNull(target);
        if (_json is not null)
        {
            // Move what the JSON writer still holds internally into the buffer
            await _json.FlushAsync(cancellationToken);
        }

        if (_buffer.Length == 0)
        {
            return;
        }

        var bytes = new ReadOnlyMemory<byte>(_buffer.GetBuffer(), 0, (int)_buffer.Length);
        _buffer.SetLength(0);
        await target.WriteAsync(bytes, cancellationToken);
    }

    /// <summary>
    ///     Releases the JSON writer and the buffer; what was not passed on with <see cref="FlushToAsync"/> is lost.
    ///     Calling it more than once is harmless.
    /// </summary>
    public void Dispose()
    {
        _json?.Dispose();
        _buffer.Dispose();
    }

    /// <summary>
    ///     Gets a cell of text that cannot be taken as a spreadsheet formula.
    /// </summary>
    /// <param name="text">The text of the cell.</param>
    /// <returns>
    ///     The text itself, or the text with a single quote in front when it starts with <c>=</c>, <c>+</c>,
    ///     <c>-</c>, <c>@</c>, a tab or a CR.
    /// </returns>
    public static string Neutralize(string text)
    {
        ArgumentNullException.ThrowIfNull(text);
        return text.Length > 0 && Array.IndexOf(FormulaStarts, text[0]) >= 0 ? "'" + text : text;
    }

    /// <summary>
    ///     Gets a CSV cell for the text: quoted when it needs to be (RFC 4180), otherwise as it is.
    /// </summary>
    /// <param name="text">The text of the cell.</param>
    /// <returns>The cell, without a separator.</returns>
    public static string Quote(string text)
    {
        ArgumentNullException.ThrowIfNull(text);
        return text.IndexOfAny(QuotedChars) < 0 ? text : "\"" + text.Replace("\"", "\"\"", StringComparison.Ordinal) + "\"";
    }

    /// <summary>
    ///     Gets the timestamp of an entry as ISO 8601 (<c>O</c>) in UTC.
    /// </summary>
    /// <param name="entry">The entry.</param>
    /// <returns>The timestamp text.</returns>
    private static string Timestamp(AuditEntry entry)
    {
        return entry.TimestampUtc.UtcDateTime.ToString("O", CultureInfo.InvariantCulture);
    }

    /// <summary>
    ///     Writes a number that may be missing as a number or a JSON null.
    /// </summary>
    /// <param name="json">The JSON writer.</param>
    /// <param name="name">The property name.</param>
    /// <param name="value">The value, or <c>null</c>.</param>
    private static void WriteNullable(Utf8JsonWriter json, string name, int? value)
    {
        if (value is { } number)
        {
            json.WriteNumber(name, number);
        }
        else
        {
            json.WriteNull(name);
        }
    }

    /// <summary>
    ///     Writes the filter object with the parts that are set.
    /// </summary>
    /// <param name="json">The JSON writer.</param>
    /// <param name="filter">The filter to describe.</param>
    private static void WriteJsonFilter(Utf8JsonWriter json, AuditFilter filter)
    {
        json.WriteStartObject("filter");
        if (filter.ProjectId is { } project)
        {
            json.WriteNumber("projectId", project);
        }

        if (filter.ReviewId is { } review)
        {
            json.WriteString("review", review);
        }

        if (filter.ActorUserId is { } actorUserId)
        {
            json.WriteNumber("actorUserId", actorUserId);
        }

        if (filter.ActorText is { } actor)
        {
            json.WriteString("actor", actor);
        }

        if (filter.Action is { } action)
        {
            json.WriteString("action", action);
        }

        if (filter.ActionPrefix is { } prefix)
        {
            json.WriteString("actionPrefix", prefix);
        }

        if (filter.From is { } from)
        {
            json.WriteString("from", from.ToString("yyyy-MM-dd", CultureInfo.InvariantCulture));
        }

        if (filter.To is { } to)
        {
            json.WriteString("to", to.ToString("yyyy-MM-dd", CultureInfo.InvariantCulture));
        }

        json.WriteEndObject();
    }

    /// <summary>
    ///     Appends one CSV line: the cells quoted as needed, separated by commas and ended with CRLF.
    /// </summary>
    /// <param name="cells">The cell texts, already neutralized where that applies.</param>
    private void AppendCsvLine(params string[] cells)
    {
        var line = string.Join(',', cells.Select(Quote)) + "\r\n";
        _buffer.Write(Utf8.GetBytes(line));
    }
}
